import { strict as assert } from 'node:assert';
import { historicalMeasurementFields, absentHistoricalFields } from './historical-measurement-fields.mjs';
const row = {page:3,cells:['156','28','Client','','2023-08-28T20:49:51','103.20','1.60','94.00','103','127','37','114','112','72','65','90']};
const converted = historicalMeasurementFields(row, 'source');
assert.equal(converted.heightCm, 160);
assert.equal(converted.waist, 94);
assert.equal(converted.thighHigh, 72);
assert.equal(converted.thighMid, 65);
assert.equal(converted.targetWeight, 90);
const cm = {...row,cells:[...row.cells]}; cm.cells[6]='165.00';
assert.equal(historicalMeasurementFields(cm,'source').heightCm,165);
const invalid={...row,cells:[...row.cells]}; invalid.cells[6]='1068.00';invalid.cells[15]='1.65';invalid.cells[7]='0.00';
const flagged=historicalMeasurementFields(invalid,'source');
assert.equal(flagged.heightCm,undefined);assert.equal(flagged.targetWeight,undefined);assert.equal(flagged.waist,undefined);
assert.equal(flagged.historicalMeasurements.height,'1068.00');assert.equal(flagged.historicalMeasurements.targetWeight,'1.65');
const existing={waist:0,leftArm:null,heightCm:172,targetWeight:80,weight:100};
const additions=absentHistoricalFields(existing,converted);
assert.equal(Object.hasOwn(additions,'waist'),false);assert.equal(Object.hasOwn(additions,'leftArm'),false);
assert.equal(Object.hasOwn(additions,'heightCm'),false);assert.equal(Object.hasOwn(additions,'targetWeight'),false);
assert.deepEqual(absentHistoricalFields({...existing,...additions},converted),{});
console.log('Historical measurements: units, raw anomaly preservation, no overwrites and idempotence OK.');
